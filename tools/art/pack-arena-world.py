#!/usr/bin/env python3
"""Pack the redrawn pixel sources and export their enlarged pixels at native size.

Rows were inspected manually: the generator did not honor equal cell dimensions.
Connected components isolate overlapping bounding boxes (frozen tree / pine).
Nearest-neighbor 1/3 export; no palette filters, smoothing, or invented details.
Alpha is normalized to the project's binary-alpha contract.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'art-source/arenas/world-20261029'
DEST = ROOT / 'assets/sprites/arenas/world-v1'
ROWS = {'hielo': [0,328,673,954,1254], 'bosque': [0,360,661,972,1254]}
NAMES = {
 'hielo': ['pillar','shards','rock','cluster','tree','pine','statue','gate',
           'fire0','fire1','fire2','fire3','off','low','ignite0','ignite1'],
 'bosque': ['oak','magic','ancient','rock','ctrl','arming','active','corrupt',
            'sealed','pulse0','pulse1','pulse2','bush0','bush1','bush2','bush3']
}

def extract(source, rows):
    out = []
    for y0,y1 in zip(rows,rows[1:]):
        row = np.array(source)[y0:y1].copy()
        opaque = row[:,:,3] > 127
        labels,n = ndimage.label(opaque, np.ones((3,3)))
        counts = np.bincount(labels.flat); counts[0] = 0
        biggest = sorted(np.argsort(counts)[-4:], key=lambda k: np.where(labels==k)[1].mean())
        centers = [np.where(labels==k)[1].mean() for k in biggest]
        owners = {int(k):i for i,k in enumerate(biggest)}
        for k in range(1,n+1):
            if k not in owners:
                owners[k] = int(np.argmin(np.abs(np.array(centers)-np.where(labels==k)[1].mean())))
        for i in range(4):
            mask = np.isin(labels, [k for k,v in owners.items() if v==i])
            pixels = row.copy(); pixels[:,:,3] = mask.astype('uint8')*255
            pixels[~mask] = 0
            im = Image.fromarray(pixels)
            out.append(im.crop(im.getbbox()))
    return out

def main():
    DEST.mkdir(parents=True,exist_ok=True)
    meta = {}
    for arena,ys in ROWS.items():
        images = extract(Image.open(SOURCE/(arena+'-source.png')).convert('RGBA'),ys)
        atlas = Image.new('RGBA',(512,512)); frames = {}
        for i,(name,im) in enumerate(zip(NAMES[arena],images)):
            # Stable bowl/plinth centers and feet across event frames. Never stretch art.
            group = images[8:] if arena=='hielo' and i>=8 else images[4:12] if arena=='bosque' and 4<=i<12 else [im]
            w=max(x.width for x in group)+8; h=max(x.height for x in group)+8
            cell=Image.new('RGBA',(w,h))
            cell.paste(im,((w-im.width)//2,h-im.height-4))
            cell=cell.resize((round(w/3),round(h/3)),Image.Resampling.NEAREST)
            w,h=cell.size
            x=(i%4)*128;y=(i//4)*128
            atlas.paste(cell,(x,y))
            frames[name]={'x':x,'y':y,'w':w,'h':h,'foot':(h-1)/h}
        atlas.save(DEST/(arena+'.png'),optimize=True)
        meta[arena]={'src':'assets/sprites/arenas/world-v1/'+arena+'.png','frames':frames}
    (DEST/'manifest.json').write_text(json.dumps(meta,indent=2)+'\n')
    (ROOT/'js/assets/arena-world-manifest.js').write_text('"use strict";\n// Generated by tools/art/pack-arena-world.py.\nconst ARENA_WORLD_MANIFEST = '+json.dumps(meta,separators=(',',':'))+';\n')
    print('Packed 32 redrawn frames at native export size; nearest-neighbor, original RGB samples, binary alpha.')
if __name__=='__main__': main()
