#!/usr/bin/env python3
"""Arma los packs world-v1 de infernal / laberinto / acuatica con los props que dibujo ANAKIN.

Fuente: art-source/arenas/anakin-20261125/crudos/<id>_s<semilla>.png (dibujos de Anakin, 512 px)
Seleccion: art-source/arenas/anakin-20261125/seleccion.json  {arena: {frame: {"crudo": nombre, "alto": px}}}
Salida: assets/sprites/arenas/world-v1/<arena>.png (512x512, celdas de 128) y las entradas de esas
arenas en manifest.json y js/assets/arena-world-manifest.js. hielo y bosque no se tocan.
Canon: alfa binario, paleta limitada, contorno oscuro de 1 px, vecino mas cercano.
"""
import json, sys
from pathlib import Path
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from pixelar import pixelar

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'art-source/arenas/anakin-20261125'
DEST = ROOT / 'assets/sprites/arenas/world-v1'

def main():
    sel = json.loads((SRC / 'seleccion.json').read_text(encoding='utf-8'))
    man_p = DEST / 'manifest.json'
    meta = json.loads(man_p.read_text(encoding='utf-8'))
    for arena, frames in sel.items():
        atlas = Image.new('RGBA', (512, 512)); out = {}
        for i, (name, f) in enumerate(frames.items()):
            im = pixelar(SRC / 'crudos' / f['crudo'], int(f['alto']), int(f.get('colores', 24)))
            if im.width > 124 or im.height > 124:
                k = min(124 / im.width, 124 / im.height)
                im = pixelar(SRC / 'crudos' / f['crudo'], int(f['alto'] * k), int(f.get('colores', 24)))
            x, y = (i % 4) * 128, (i // 4) * 128
            atlas.paste(im, (x, y))
            out[name] = {'x': x, 'y': y, 'w': im.width, 'h': im.height, 'foot': (im.height - 1) / im.height}
        atlas.save(DEST / (arena + '.png'), optimize=True)
        meta[arena] = {'src': 'assets/sprites/arenas/world-v1/' + arena + '.png', 'frames': out}
    man_p.write_text(json.dumps(meta, indent=2) + '\n')
    (ROOT / 'js/assets/arena-world-manifest.js').write_text('"use strict";\n// Generated by tools/art/pack-arena-world.py (hielo, bosque) and tools/art/anakin/pack-anakin-world.py (infernal, laberinto, acuatica).\nconst ARENA_WORLD_MANIFEST = ' + json.dumps(meta, separators=(',', ':')) + ';\n')
    print('packs:', ', '.join(sel))

if __name__ == '__main__':
    main()
