import math


def _grid():
    return [['.'] * 12 for _ in range(12)]


def _put(g, x, y, c):
    if 0 <= x < 12 and 0 <= y < 12:
        g[y][x] = c


def _disc(g, cx, cy, r, c):
    for y in range(12):
        for x in range(12):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
                g[y][x] = c


def _ring(g, cx, cy, r0, r1, c):
    for y in range(12):
        for x in range(12):
            d = (x - cx) ** 2 + (y - cy) ** 2
            if r0 * r0 <= d <= r1 * r1:
                g[y][x] = c


def _line(g, x0, y0, x1, y1, c, t=1):
    n = max(abs(x1 - x0), abs(y1 - y0)) or 1
    for i in range(n + 1):
        x = round(x0 + (x1 - x0) * i / n)
        y = round(y0 + (y1 - y0) * i / n)
        _put(g, x, y, c)
        if t > 1:
            _put(g, x + 1, y, c)


def _rows(g):
    return [''.join(r) for r in g]


def _worldstep():
    g = _grid()
    _ring(g, 4.2, 5.5, 2.6, 4.2, '#')
    _ring(g, 7.8, 5.5, 2.6, 4.2, 'a')
    return _rows(g)


def _brokenclock():
    g = _grid()
    _ring(g, 5.5, 5.5, 3.6, 5.5, '#')
    _line(g, 5, 5, 5, 2, 'a')
    _line(g, 5, 5, 8, 6, 'a')
    _line(g, 7, 0, 5, 4, 'k')
    _line(g, 5, 4, 7, 7, 'k')
    _line(g, 7, 7, 5, 11, 'k')
    return _rows(g)


def _splitseconds():
    g = _grid()
    _ring(g, 5.5, 5.5, 3.6, 5.5, '#')
    for y in range(12):
        for x in range(12):
            if x >= 6:
                if g[y][x] == '#':
                    g[y][x] = '.'
    h = _grid()
    _ring(h, 5.5, 5.5, 3.6, 5.5, 'a')
    for y in range(12):
        for x in range(12):
            if x >= 6 and h[y][x] == 'a' and y + 1 < 12:
                g[y + 1][x] = 'a'
    _line(g, 5, 5, 5, 2, '#')
    return _rows(g)


def _pocketwatch():
    g = _grid()
    _disc(g, 5.5, 6.5, 4.6, '#')
    _ring(g, 5.5, 6.5, 3.0, 3.4, 'k')
    _line(g, 5, 6, 5, 4, 'a')
    _line(g, 6, 6, 8, 7, 'a')
    for x, y in ((4, 0), (5, 0), (6, 0), (7, 0), (5, 1), (6, 1)):
        _put(g, x, y, 'a')
    return _rows(g)


